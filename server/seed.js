// Deterministic PRNG so seeds are reproducible
function rng(seed) { let s = seed; return () => (s = (s * 16807) % 2147483647) / 2147483647; }

export function seed({ reset = false } = {}) {
  const r = rng(42);
  const has = db.prepare('SELECT COUNT(*) AS c FROM products').get().c;
  if (has && !reset) return false;

  const tx = db.transaction(() => {
    if (reset) {
      for (const t of ['order_events', 'order_items', 'orders', 'reviews', 'wishlist', 'products', 'coupons', 'subscribers', 'inquiries']) db.exec(`DELETE FROM ${t}`);
      db.exec("DELETE FROM users WHERE role = 'customer'");
      db.exec("DELETE FROM sqlite_sequence WHERE name IN ('products','orders','order_items','reviews','order_events')");
    }

    const insP = db.prepare(`INSERT INTO products (slug,name,category,collection,badge,price,original_price,material,description,details,images,stock,featured,is_new,sold,created_at)
      VALUES (@slug,@name,@category,@collection,@badge,@price,@original_price,@material,@description,@details,@images,@stock,@featured,@is_new,@sold,@created_at)`);
    const insR = db.prepare(`INSERT INTO reviews (product_id,author,location,rating,title,body,verified,created_at) VALUES (?,?,?,?,?,?,1,?)`);

    PRODUCTS.forEach((p, i) => {
      const daysAgo = p.isNew ? Math.floor(r() * 12) : 20 + Math.floor(r() * 120);
      const { lastInsertRowid: pid } = insP.run({
        slug: p.slug || slugify(p.name), name: p.name, category: p.category, collection: p.collection, badge: p.badge,
        price: p.price, original_price: p.original ?? p.price, material: p.material, description: p.description,
        // Imported items only list what the owner stated; generic care claims stay on the hand-written catalogue.
        details: JSON.stringify(p.source ? (p.material ? [`Material: ${p.material}`] : []) : [`Material: ${p.material}`, ...DETAILS[p.category]]),
        images: JSON.stringify(p.images), stock: p.stock ?? 10,
        featured: p.featured || 0, is_new: p.isNew || 0, sold: p.source ? 0 : 20 + Math.floor(r() * 180),
        created_at: p.source?.date ? `${p.source.date} 12:00:00` : new Date(Date.now() - daysAgo * 864e5).toISOString().slice(0, 19).replace('T', ' '),
      });
      if (p.source) return; // no made-up reviews for imported items
      const n = 2 + Math.floor(r() * 5);
      for (let k = 0; k < n; k++) {
        const [author, loc] = NAMES[Math.floor(r() * NAMES.length)];
        const [title, body] = REVIEW_TEXT[Math.floor(r() * REVIEW_TEXT.length)];
        const rating = r() < 0.75 ? 5 : r() < 0.8 ? 4 : 3;
        const when = new Date(Date.now() - Math.floor(r() * 90) * 864e5).toISOString().slice(0, 19).replace('T', ' ');
        insR.run(pid, author, loc, rating, title, body, when);
      }
    });

    const insC = db.prepare('INSERT OR REPLACE INTO coupons (code,description,type,value,min_subtotal,max_discount,active) VALUES (?,?,?,?,?,?,1)');
    insC.run('CHATIM15', 'Flat 15% off for new customers', 'percent', 15, 0, 1500);
    insC.run('WELCOME100', '₹100 off on orders above ₹999', 'flat', 100, 999, null);
    insC.run('PUJO25', '25% off festive orders above ₹2,499 (max ₹1,000)', 'percent', 25, 2499, 1000);

    // Demo customers & historical orders so the admin dashboard has data
    const demoHash = bcrypt.hashSync(Math.random().toString(36) + Date.now(), 10); // unusable random password
    const insU = db.prepare("INSERT OR IGNORE INTO users (name,email,phone,password_hash,role,created_at) VALUES (?,?,?,?, 'customer', ?)");
    const customers = NAMES.slice(0, 10).map(([name, loc], i) => {
      const email = `${slugify(name).replace(/-/g, '.')}@example.com`;
      insU.run(name, email, `98300${String(10000 + i * 731).slice(0, 5)}`, demoHash,
        new Date(Date.now() - (40 + i * 3) * 864e5).toISOString().slice(0, 19).replace('T', ' '));
      return { ...db.prepare('SELECT * FROM users WHERE email = ?').get(email), loc };
    });

    const products = db.prepare('SELECT * FROM products WHERE price > 0').all();
    const insO = db.prepare(`INSERT INTO orders (order_number,user_id,email,name,phone,address,subtotal,discount,shipping,total,coupon_code,shipping_method,payment_method,payment_status,status,created_at,updated_at)
      VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`);
    const insI = db.prepare('INSERT INTO order_items (order_id,product_id,name,image,price,quantity) VALUES (?,?,?,?,?,?)');
    const insE = db.prepare('INSERT INTO order_events (order_id,status,note,created_at) VALUES (?,?,?,?)');
    const FLOW = ['placed', 'confirmed', 'packed', 'shipped', 'delivered'];

    for (let i = 0; i < 46; i++) {
      const c = customers[Math.floor(r() * customers.length)];
      const daysAgo = Math.floor(r() * 30);
      const created = new Date(Date.now() - daysAgo * 864e5 - Math.floor(r() * 864e5));
      const ts = created.toISOString().slice(0, 19).replace('T', ' ');
      const lines = []; const cnt = 1 + Math.floor(r() * 3);
      for (let k = 0; k < cnt; k++) {
        const p = products[Math.floor(r() * products.length)];
        if (!lines.find((l) => l.p.id === p.id)) lines.push({ p, q: 1 + (r() < 0.2 ? 1 : 0) });
      }
      const subtotal = lines.reduce((s, l) => s + l.p.price * l.q, 0);
      const useCoupon = r() < 0.3;
      const discount = useCoupon ? Math.min(Math.round(subtotal * 0.15), 1500) : 0;
      const shipping = subtotal - discount >= 999 ? 0 : 79;
      const progress = daysAgo > 6 ? 4 : Math.min(4, Math.floor(daysAgo / 1.5));
      const status = r() < 0.04 ? 'cancelled' : FLOW[progress];
      const pay = ['upi', 'card', 'cod'][Math.floor(r() * 3)];
      const orderNo = `CH${created.toISOString().slice(2, 10).replace(/-/g, '')}${String(1000 + i)}`;
      const { lastInsertRowid: oid } = insO.run(orderNo, c.id, c.email, c.name, c.phone,
        JSON.stringify({ line1: `${12 + i} Lake View Road`, line2: '', city: c.loc.split(', ').pop(), state: 'West Bengal', pincode: '700091' }),
        subtotal, discount, shipping, subtotal - discount + shipping, useCoupon ? 'CHATIM15' : null,
        'standard', pay, pay === 'cod' && status !== 'delivered' ? 'pending' : 'paid', status, ts, ts);
      lines.forEach((l) => insI.run(oid, l.p.id, l.p.name, JSON.parse(l.p.images)[0], l.p.price, l.q));
      const steps = status === 'cancelled' ? ['placed', 'cancelled'] : FLOW.slice(0, progress + 1);
      steps.forEach((s, k) => insE.run(oid, s, null, new Date(created.getTime() + k * 864e5 * 1.2).toISOString().slice(0, 19).replace('T', ' ')));
    }

    db.prepare('INSERT OR IGNORE INTO subscribers (email) VALUES (?)').run('newsletter.fan@example.com');
    db.prepare("INSERT INTO inquiries (name,phone,topic,message) VALUES (?,?,?,?)")
      .run('Nandini Das', '+91 98300 00000', 'Bridal / Trousseau Styling', 'Looking for a full bridal set for February. Can we do a video call?');
  });
  tx();
  return true;
}

/** Make sure an admin account exists using ADMIN_EMAIL / ADMIN_PASSWORD from the environment. */
export function ensureAdmin() {
  const email = process.env.ADMIN_EMAIL;
  const password = process.env.ADMIN_PASSWORD;
  if (!email || !password) return;
  const existing = db.prepare('SELECT id FROM users WHERE email = ?').get(email);
  const hash = bcrypt.hashSync(password, 10);
  if (existing) db.prepare("UPDATE users SET password_hash = ?, role = 'admin' WHERE id = ?").run(hash, existing.id);
  else db.prepare("INSERT INTO users (name,email,password_hash,role) VALUES ('Chatim Admin', ?, ?, 'admin')").run(email, hash);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await import('dotenv/config');
  const did = seed({ reset: process.argv.includes('--reset') });
  ensureAdmin();
  console.log(did ? '✔ Database seeded' : 'Database already has data (use --reset to reseed)');
}
